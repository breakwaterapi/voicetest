"""
Pydantic models for scenario YAML files.

Sub-models use extra='forbid' to catch YAML typos early.
The top-level Scenario uses extra='ignore' so compiler-generated scenarios
can carry forward-compatible fields without breaking older runners.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, field_validator, model_validator


class _StrictModel(BaseModel):
    """Base with extra='forbid' so unknown YAML keys raise ValidationError."""

    model_config = {"extra": "forbid"}


# ---------------------------------------------------------------------------
# Sub-models
# ---------------------------------------------------------------------------


class Persona(_StrictModel):
    system_prompt: str
    goal: str
    difficult_behaviors: list[str]
    ground_truth: dict[str, Any] = {}

    @field_validator("difficult_behaviors")
    @classmethod
    def must_be_nonempty(cls, v: list[str]) -> list[str]:
        if not v:
            raise ValueError(
                "difficult_behaviors must be non-empty — "
                "a persona with zero difficult behaviors is a people-pleaser and will not test anything"
            )
        return v


class NoiseConfig(_StrictModel):
    enabled: bool = False
    profile: Literal["cafe", "street", "car"] = "cafe"
    level_db: float = -12.0


class BargeInConfig(_StrictModel):
    enabled: bool = False
    trigger_after_agent_speaks_ms: int = 800
    on_agent_turn: int = 2
    caller_says: str = ""


class LatencyThresholds(_StrictModel):
    p50_warn_ms: int = 800
    p95_warn_ms: int = 1500


class ScoringConfig(_StrictModel):
    objective: str
    pass_criteria: list[str] = []
    latency: LatencyThresholds = LatencyThresholds()


class Limits(_StrictModel):
    max_duration_s: int = 180
    max_turns: int = 25


# ---------------------------------------------------------------------------
# Top-level Scenario
# ---------------------------------------------------------------------------


class Scenario(BaseModel):
    model_config = {"extra": "ignore"}

    id: str
    category: str  # open string — no longer restricted to 3 builtin values
    title: str
    version: int = 1
    group: str = ""  # battery group this belongs to (baseline, confused_caller, …)
    node_id: str = ""  # AgentModel graph node this scenario targets, if grounded
    compiler_version: int | None = None  # set when generated by ScenarioCompiler
    persona: Persona
    noise: NoiseConfig = NoiseConfig()
    barge_in: BargeInConfig = BargeInConfig()
    scoring: ScoringConfig
    limits: Limits = Limits()

    @model_validator(mode="before")
    @classmethod
    def _handle_barge_in_key(cls, data: dict) -> dict:
        # YAML key is `barge_in` but also accept `barge-in` for convenience
        if "barge-in" in data and "barge_in" not in data:
            data["barge_in"] = data.pop("barge-in")
        return data
